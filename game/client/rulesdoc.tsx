/**
 * 文字版完整规则：从规则图解右上角「完整规则」打开，盖在图解上面的一页长文（不缩放，按手机原尺寸排）。
 * 「」里的词加粗。内容按引擎的实际规则写：改了规则记得也改这里。
 */

import { useEffect, useRef } from 'preact/hooks';

/** 「」里的部分加粗（括号本身不加粗）。 */
export function Rich({ text }: { text: string }) {
  return (
    <>
      {text
        .split(/(「[^」]*」)/g)
        .filter(Boolean)
        .map((p, i) =>
          p.startsWith('「') && p.endsWith('」') ? (
            <span key={i}>
              「<b>{p.slice(1, -1)}</b>」
            </span>
          ) : (
            <span key={i}>{p}</span>
          ),
        )}
    </>
  );
}

