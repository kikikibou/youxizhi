function BlockView({ b }: { b: Block }) {
  if ('p' in b)
    return (
      <p>
        <Rich text={b.p} />
      </p>
    );
  if ('note' in b)
    return (
      <p class="b-doc-note">
        ※ <Rich text={b.note} />
      </p>
    );
  if ('ul' in b || 'ol' in b) {
    const items = 'ul' in b ? b.ul : b.ol;
    const List = 'ul' in b ? 'ul' : 'ol';
    return (
      <List>
        {items.map((t, k) => (
          <li key={k}>
            <Rich text={t} />
          </li>
        ))}
      </List>
    );
  }
  return (
    <table>
      <thead>
        <tr>
          {b.table.head.map((h) => (
            <th key={h}>{h}</th>
          ))}
        </tr>
      </thead>
      <tbody>
        {b.table.rows.map((r, k) => (
          <tr key={k}>
            {r.map((c, j) => (
              <td key={j}>{c}</td>
            ))}
          </tr>
        ))}
      </tbody>
    </table>
  );
}

export function RulesDoc({ onClose }: { onClose: () => void }) {
  const box = useRef<HTMLDivElement>(null);
  useEffect(() => {
    const on = (e: KeyboardEvent) => {
      if (e.key === 'Escape') {
        e.stopPropagation();
        onClose();
      }
    };
    window.addEventListener('keydown', on, true);
    box.current?.focus();
    return () => window.removeEventListener('keydown', on, true);
  }, []);
  const jump = (k: number) => box.current?.querySelector(`#b-doc-${k}`)?.scrollIntoView({ behavior: 'smooth', block: 'start' });
  return (
    <div class="b-doc" role="dialog" aria-modal="true" aria-label="完整规则" ref={box} tabIndex={-1}>
      <header class="b-doc-bar">
        <button type="button" class="b-doc-back" onClick={onClose}>
          ← 回到图解
        </button>
        <span class="b-doc-bar-t">完整规则</span>
      </header>
      <article class="b-doc-page">
        <p class="b-doc-k">大国小国 · 规则</p>
        <h1>完整规则</h1>
        <nav class="b-doc-toc" aria-label="目录">
          {SECTIONS.map((s, k) => (
            <button type="button" key={k} onClick={() => jump(k)}>
              <b>{String(k + 1).padStart(2, '0')}</b>
              {s.title}
            </button>
          ))}
        </nav>
        {SECTIONS.map((s, k) => (
          <section key={k} id={`b-doc-${k}`}>
            <h2>
              <b>{String(k + 1).padStart(2, '0')}</b>
              {s.title}
            </h2>
            {s.blocks.map((b, j) => (
              <BlockView key={j} b={b} />
            ))}
          </section>
        ))}
        <button type="button" class="b-doc-end" onClick={onClose}>
          回到图解
        </button>
      </article>
    </div>
  );
}
